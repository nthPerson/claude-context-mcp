def test_tool_use_and_tool_results() -> None:
    chunk = parse(
        assistant(
            [
                {"type": "text", "text": "Let me look."},
                {"type": "tool_use", "id": "toolu_A", "name": "Read", "input": {"file_path": "/home/user/a.py"}},
                {"type": "tool_use", "id": "toolu_B", "name": "Bash", "input": {"command": "false"}},
            ],
            1,
        ),
        user(
            [
                {"type": "tool_result", "tool_use_id": "toolu_A", "content": "print('hi')"},
                {
                    "type": "tool_result",
                    "tool_use_id": "toolu_B",
                    "is_error": True,
                    "content": [
                        {"type": "text", "text": "exit 1"},
                        {"type": "image", "source": {}},
                        {"type": "tool_reference", "tool_name": "WebSearch"},
                        {"type": "mystery"},
                    ],
                },
            ],
            2,
        ),
    )
    roles = [(m.role, m.block_index) for m in chunk.messages]
    assert roles == [
        (ROLE_ASSISTANT, 0),
        (ROLE_TOOL_CALL, 1),
        (ROLE_TOOL_CALL, 2),
        (ROLE_TOOL_RESULT, 0),
        (ROLE_TOOL_RESULT, 1),
    ]
    read, bash = chunk.messages[1], chunk.messages[2]
    assert (read.tool_name, read.tool_use_id, read.text) == ("Read", "toolu_A", "Read: /home/user/a.py")
    assert bash.text == "Bash: false"
    ok, err = chunk.messages[3], chunk.messages[4]
    assert (ok.tool_use_id, ok.text, ok.is_error) == ("toolu_A", "print('hi')", False)
    assert err.is_error
    assert err.text == "exit 1\n[image]\n[tool_reference: WebSearch]"
    assert not any(m.is_prompt for m in chunk.messages)


def test_tool_result_truncated_in_chunk_but_not_in_full_parse() -> None:
    body = "line of output\n" * 1000
    record = user([{"type": "tool_result", "tool_use_id": "toolu_X", "content": body}])
    m = parse(record).messages[0]
    assert len(m.text) == TOOL_RESULT_INDEX_CHARS
    assert m.text_len == len(body)
    full = parse_line_full(json.dumps(record).encode())
    assert full[0].text == body
    assert full[0].text_len == len(body)


def test_render_tool_call() -> None:
    assert render_tool_call("Bash", {"command": "ls", "description": "List files"}) == "Bash: List files"
