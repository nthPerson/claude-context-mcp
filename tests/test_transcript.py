def test_subagent_facts_and_meta(tmp_path: Path) -> None:
    agent = "a0123456789abcdef"
    chunk = parse(
        user("Investigate the parser", 1, isSidechain=True, agentId=agent),
        assistant([{"type": "text", "text": "Done."}], 2, isSidechain=True, agentId=agent),
    )
    assert chunk.facts.agent_id == agent
    assert chunk.facts.session_id == SESSION

    meta = tmp_path / f"agent-{agent}.meta.json"
    meta.write_text(json.dumps({"agentType": "Explore", "description": "Investigate the parser"}))
    assert load_subagent_meta(meta) == {"agentType": "Explore", "description": "Investigate the parser"}
    (tmp_path / "bad.json").write_text("{nope")
    (tmp_path / "list.json").write_text("[1]")
    assert load_subagent_meta(tmp_path / "bad.json") == {}
    assert load_subagent_meta(tmp_path / "list.json") == {}
    assert load_subagent_meta(tmp_path / "missing.json") == {}


def test_parse_line_full_matches_chunk_addressing() -> None:
    record = assistant(
        [
            {"type": "thinking", "thinking": "x", "signature": "y"},
            {"type": "tool_use", "id": "toolu_Q", "name": "Glob", "input": {"pattern": "*.md"}},
        ]
    )
    chunk_msgs = parse(record).messages
    full = parse_line_full(json.dumps(record).encode() + b"\n")
    assert [(m.role, m.block_index, m.text) for m in full] == [
        (m.role, m.block_index, m.text) for m in chunk_msgs
    ]
    assert parse_line_full(b"garbage") == []
