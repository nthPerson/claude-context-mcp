def rec(type_: str, n: int = 0, **fields: object) -> dict:
    base = {
        "type": type_,
        "uuid": f"uuid-{type_}-{n}",
        "parentUuid": None,
        "timestamp": f"2026-01-02T03:04:{n:02d}.000Z",
        "sessionId": SESSION,
        "cwd": "/home/user/project",
        "gitBranch": "main",
        "version": "2.0.0",
        "entrypoint": "cli",
        "isSidechain": False,
    }
    base.update(fields)
    return base


def user(content: object, n: int = 0, **fields: object) -> dict:
    return rec("user", n, message={"role": "user", "content": content}, **fields)


def assistant(blocks: list, n: int = 0, **fields: object) -> dict:
    return rec("assistant", n, message={"role": "assistant", "content": blocks}, **fields)


def jsonl(*records: object) -> bytes:
    return b"".join(json.dumps(r).encode() + b"\n" for r in records)


def parse(*records: object):
    return parse_chunk(jsonl(*records))


def texts(chunk) -> list[str]:
    return [m.text for m in chunk.messages]


# --- user content -------------------------------------------------------------------------


def test_string_and_list_content_prompts() -> None:
    chunk = parse(
        user("fix the failing test", 1),
        user([{"type": "text", "text": "first"}, {"type": "text", "text": "second"}], 2),
    )
    assert [(m.role, m.text, m.is_prompt) for m in chunk.messages] == [
        (ROLE_USER, "fix the failing test", True),
        (ROLE_USER, "first\n\nsecond", True),
    ]
    m = chunk.messages[0]
    assert m.uuid == "uuid-user-1"
    assert m.ts == "2026-01-02T03:04:01.000Z"
    assert m.text_len == len(m.text)


