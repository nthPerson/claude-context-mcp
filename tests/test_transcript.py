def test_partial_trailing_line_and_resume() -> None:
    data = jsonl(user("one", 1), user("two", 2), user("three", 3))
    first_two = len(jsonl(user("one", 1), user("two", 2)))
    cut = first_two + 10  # mid-way through the third line

    a = parse_chunk(data[:cut], base_offset=0)
    assert a.consumed == first_two
    assert texts(a) == ["one", "two"]
    assert [m.line_offset for m in a.messages] == [0, len(jsonl(user("one", 1)))]

    b = parse_chunk(data[a.consumed :], base_offset=a.consumed)
    assert b.consumed == len(data) - a.consumed
    assert texts(b) == ["three"]
    assert b.messages[0].line_offset == first_two
    assert data[b.messages[0].line_offset :].startswith(b'{"type": "user"')


def test_no_complete_line_consumes_nothing() -> None:
    chunk = parse_chunk(b'{"type": "user", "mess', base_offset=100)
    assert chunk.consumed == 0 and chunk.messages == []


def test_malformed_and_odd_lines() -> None:
    data = (
        jsonl(user("before", 1))
        + b"{not json\n"
        + b'"a bare string"\n'
        + b"[1, 2]\n"
        + b"\n"
        + b'{"type": "user", "message": {"content": "caf\xff\xfe"}}\n'
        + jsonl(
            {"type": "user"},
            {"type": "user", "message": "not a dict"},
            {"type": "user", "message": {"content": 42}},
            {"type": "assistant", "message": {"content": None}},
            {"type": "assistant", "message": {"content": [None, 3, {"type": "text", "text": 5}]}},
            {"no_type": True},
            user("after", 2),
        )
    )
    chunk = parse_chunk(data)
    assert chunk.consumed == len(data)
    assert chunk.malformed_lines == 3
    assert texts(chunk) == ["before", "caf��", "after"]
    assert chunk.unknown_types == {"<missing>": 1}


